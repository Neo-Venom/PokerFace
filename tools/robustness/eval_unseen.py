"""Evaluate main.py against a generated unseen dataset (leaks, medical retention, determinism, secret isolation)."""
from __future__ import annotations

import argparse
import base64
import binascii
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import unicodedata
from collections import Counter
from pathlib import Path

_B64 = re.compile(r"[A-Za-z0-9+/]{24,}={0,2}")


def _norm(s: str) -> str:
    return " ".join(unicodedata.normalize("NFKC", s).casefold().split())


def _read_with_b64(p: Path) -> str:
    raw = p.read_bytes()
    txt = raw.decode("utf-8", errors="replace")
    extras = []
    for m in _B64.finditer(txt):
        tok = m.group(0)
        try:
            extras.append(base64.b64decode(tok + "=" * (-len(tok) % 4)).decode("utf-8", errors="ignore"))
        except (binascii.Error, ValueError):
            pass
    return txt + "\n" + "\n".join(extras) if extras else txt


def _tree_digest(out: Path) -> str:
    h = hashlib.sha256()
    for name in ("sanitized", "records.jsonl"):
        p = out / name
        items = sorted(p.rglob("*")) if p.is_dir() else ([p] if p.exists() else [])
        for f in items:
            if f.is_file():
                h.update(f.relative_to(out).as_posix().encode() + b"\0" + f.read_bytes() + b"\0")
    return h.hexdigest()


def _run_pipeline(repo: Path, inp: Path, out: Path, secret: str) -> subprocess.CompletedProcess:
    if out.exists():
        shutil.rmtree(out)
    env = dict(os.environ, RAKSHA_SECRET=secret)
    return subprocess.run(
        [sys.executable, str(repo / "main.py"), "--input", str(inp), "--output", str(out)],
        cwd=repo,
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )


def main() -> int:
    ap = argparse.ArgumentParser(description="Evaluate RakshaGuard on unseen synthetic dataset")
    ap.add_argument("--data", default=".unseen_data", help="Folder generated by gen_unseen.py")
    ap.add_argument("--out-prefix", default=".unseen_out", help="Prefix for run A/B/C output dirs")
    a = ap.parse_args()

    repo = Path(__file__).resolve().parents[2]
    data_dir = Path(a.data)
    inp = data_dir / "input"
    truth = json.loads((data_dir / "truth.json").read_text(encoding="utf-8"))

    out_a = Path(f"{a.out_prefix}_a")
    out_b = Path(f"{a.out_prefix}_b")
    out_c = Path(f"{a.out_prefix}_c")

    res_a = _run_pipeline(repo, inp, out_a, "unseen-secret-alpha")
    res_b = _run_pipeline(repo, inp, out_b, "unseen-secret-alpha")
    res_c = _run_pipeline(repo, inp, out_c, "unseen-secret-beta")

    if res_a.returncode != 0:
        print("FAIL: main.py exited with", res_a.returncode, res_a.stderr)
        return 1

    det_same = _tree_digest(out_a) == _tree_digest(out_b)
    diff_secret_diff = _tree_digest(out_a) != _tree_digest(out_c)

    report = json.loads((out_a / "report.json").read_text(encoding="utf-8"))
    renamed = {e.get("input_sha256"): e.get("output") for e in report.get("files") or []}
    reasons = Counter(e.get("reason") for e in report.get("files") or [] if e.get("status") != "sanitized")

    leaks, kept = Counter(), Counter()
    by_script, tot_script = Counter(), Counter()
    by_channel, tot_channel = Counter(), Counter()
    pres_ok = pres_all = 0
    examples = []

    san = out_a / "sanitized"
    for rel, f in truth["files"].items():
        declared = renamed.get(f["sha256"])
        out_rel = str(declared).replace("sanitized/", "", 1) if declared else rel
        p = san / out_rel
        exists = p.is_file()
        text = _norm(_read_with_b64(p)) if exists else ""
        fname = _norm(out_rel)
        for _loc, u in f["units"].items():
            for e in u.get("entities", []):
                if e["type"] == "CANARY":
                    continue
                tot_script[e["script"]] += 1
                tot_channel[e["channel"]] += 1
                surf = _norm(e["surface"])
                hay = fname if e["channel"] == "filename" else text
                hit = (bool(surf) and surf in hay) if (exists or e["channel"] == "filename") else False
                if hit:
                    leaks[e["type"]] += 1
                    by_script[e["script"]] += 1
                    by_channel[e["channel"]] += 1
                    examples.append((e["type"], e["script"], e["channel"], rel, e["surface"]))
                else:
                    kept[e["type"]] += 1
            if exists:
                for pv in u.get("preserve", []):
                    pres_all += 1
                    pres_ok += _norm(pv["text"]) in text

    all_out_txt = _norm(
        "\n".join(
            [p.name + "\n" + _read_with_b64(p) for p in out_a.rglob("*") if p.is_file()]
        )
    )
    canary_hits = [c for c in truth.get("canaries", []) if _norm(c) in all_out_txt]

    tot_ent = sum(leaks.values()) + sum(kept.values())
    print("=" * 64)
    print(" UNSEEN DATASET ROBUSTNESS EVALUATION")
    print("=" * 64)
    print(f"Determinism (same secret A == B): {det_same}")
    print(f"Different secret output differs : {diff_secret_diff} (note: M1 has null pseudonyms/no date shifts yet)")
    print(f"Quarantined reasons             : {dict(reasons)}")
    print(f"PII leaked                      : {sum(leaks.values())} / {tot_ent} ({100 * sum(leaks.values()) / max(1, tot_ent):.1f}%)")
    for t in sorted(set(leaks) | set(kept), key=lambda k: -leaks[k]):
        n = leaks[t] + kept[t]
        print(f"  {t:<16} {leaks[t]:>3} / {n:<3} ({100 * leaks[t] / n:5.1f}%)")
    print("By script :", ", ".join(f"{s} {100 * by_script[s] / max(1, tot_script[s]):.1f}%" for s in tot_script))
    print("By channel:", ", ".join(f"{c} {100 * by_channel[c] / max(1, tot_channel[c]):.1f}%" for c in tot_channel))
    print(f"Canaries leaked                 : {len(canary_hits)} / {len(truth.get('canaries', []))} {canary_hits}")
    print(f"Medical values kept             : {pres_ok} / {pres_all} ({100 * pres_ok / max(1, pres_all):.1f}%)")
    if examples:
        print("Leak examples:")
        for ex in examples[:15]:
            print(" ", " | ".join(ex))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
